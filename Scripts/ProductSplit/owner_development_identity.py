"""One explicitly task-owned Apple Development identity via documented REST.

Existing identities are never revoked. The generated private key remains only in
the runner's owned mode-0700 task directory until that exact new certificate has
been revoked; it is never placed in logs or workflow artifacts.
"""
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import secrets
import time
import urllib.error
import urllib.request
import uuid

from audit_release_resources import decode
from cross_app_owner_provisioning import (
    _development_certificates, _private_output, _revoke_temporary_development_certificate,
)
from resolve_signing_profiles import resource_id


class CertificateCreationRejected(RuntimeError):
    def __init__(self, status, codes):
        super().__init__("Apple certificate creation rejected (HTTP " + str(status) + ")")
        self.status, self.codes = status, codes


class CertificateCreationUncertain(RuntimeError):
    pass


def _public_key_bytes(key):
    from cryptography.hazmat.primitives import serialization
    return key.public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)


def _owned_certificate_fact(record, public_key_sha256, before_ids, team):
    """A new resource must contain the public key generated by this task."""
    from cryptography import x509
    from cryptography.x509.oid import NameOID
    identifier = resource_id(record["id"])
    attributes = record.get("attributes", {})
    if identifier in before_ids or attributes.get("certificateType") != "DEVELOPMENT":
        raise ValueError("Only this task's new Apple Development identity is eligible")
    raw = decode(attributes["certificateContent"])
    certificate = x509.load_der_x509_certificate(raw)
    if hashlib.sha256(_public_key_bytes(certificate.public_key())).hexdigest() != public_key_sha256:
        raise ValueError("The certificate does not match this task's generated private key")
    teams = [value.value for value in certificate.subject.get_attributes_for_oid(NameOID.ORGANIZATIONAL_UNIT_NAME)]
    if team not in teams:
        raise ValueError("The created certificate belongs to a different owner team")
    before = getattr(certificate, "not_valid_before_utc", None)
    after = getattr(certificate, "not_valid_after_utc", None)
    before = before or certificate.not_valid_before.replace(tzinfo=timezone.utc)
    after = after or certificate.not_valid_after.replace(tzinfo=timezone.utc)
    if not before <= datetime.now(timezone.utc) < after:
        raise ValueError("The created development identity is not currently valid")
    return {"resource_id": identifier, "certificate_type": "DEVELOPMENT",
            "public_certificate_sha256": hashlib.sha256(raw).hexdigest(),
            "public_certificate_sha1": hashlib.sha1(raw).hexdigest().upper(),
            "public_key_sha256": public_key_sha256, "expiration": after.isoformat(),
            "created_after_probe_started": True, "owner_team_matches": True,
            "public_key_matches_task_owned_private_key": True}


def _public_error_codes(raw):
    try:
        values = json.loads(raw).get("errors", [])
        return sorted({row["code"] for row in values if isinstance(row, dict)
                       and isinstance(row.get("code"), str)
                       and re.fullmatch(r"[A-Za-z0-9_.-]+", row["code"])})
    except (ValueError, TypeError, KeyError):
        return []


def _post_certificate(csr):
    """A single POST; uncertain outcomes are reconciled by public key, not retried."""
    import jwt
    now = int(time.time())
    token = jwt.encode(
        {"iss": os.environ["ASC_ISSUER_ID"], "iat": now, "exp": now + 600,
         "aud": "appstoreconnect-v1"}, decode(os.environ["ASC_KEY_P8"]),
        algorithm="ES256", headers={"kid": os.environ["ASC_KEY_ID"], "typ": "JWT"})

    class NoRedirect(urllib.request.HTTPRedirectHandler):
        def redirect_request(self, req, fp, code, msg, headers, newurl):
            return None

    request = urllib.request.Request(
        "https://api.appstoreconnect.apple.com/v1/certificates",
        data=json.dumps({"data": {"type": "certificates",
            "attributes": {"certificateType": "DEVELOPMENT", "csrContent": csr}}}).encode(),
        headers={"Authorization": "Bearer " + token, "Content-Type": "application/json"}, method="POST")
    try:
        with urllib.request.build_opener(NoRedirect).open(request, timeout=30) as response:
            raw = response.read()
            if response.status != 201:
                raise CertificateCreationUncertain("Unexpected Apple certificate creation response")
        return json.loads(raw)["data"]
    except urllib.error.HTTPError as error:
        if 400 <= error.code < 500:
            raise CertificateCreationRejected(error.code, _public_error_codes(error.read())) from None
        raise CertificateCreationUncertain("Apple certificate creation outcome requires reconciliation") from None
    except (OSError, TimeoutError, ValueError, KeyError):
        raise CertificateCreationUncertain("Apple certificate creation outcome requires reconciliation") from None


def create_task_development_identity(work, *, keychain, keychain_password, team, before_ids, receipt):
    from cryptography import x509
    from cryptography.hazmat.primitives import hashes, serialization
    from cryptography.hazmat.primitives.asymmetric import rsa
    from cryptography.hazmat.primitives.serialization.pkcs12 import serialize_key_and_certificates
    from cryptography.x509.oid import NameOID
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    key_sha = hashlib.sha256(_public_key_bytes(key.public_key())).hexdigest()
    run_id = os.environ["GITHUB_RUN_ID"]
    root = Path.home() / "Library/Application Support/HanlinSigningTasks"
    root.mkdir(mode=0o700, parents=True, exist_ok=True)
    task = root / ("owner-" + str(run_id) + "-" + uuid.uuid4().hex)
    task.mkdir(mode=0o700)
    private_path = task / "development-private.pem"
    descriptor = os.open(private_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, "wb") as stream:
        stream.write(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                       serialization.NoEncryption()))
    receipt.update(status="GENERATED_TASK_KEY", public_key_sha256=key_sha,
                   private_key_path=str(private_path), private_key_export="NOT_REQUESTED",
                   existing_certificate_ids_preserved=sorted(before_ids),
                   source="DOCUMENTED_POST_V1_CERTIFICATES_CURRENT_DEVELOPMENT_TYPE")
    csr = (x509.CertificateSigningRequestBuilder()
           .subject_name(x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "Hanlin MiniApps owner " + str(run_id))]))
           .sign(key, hashes.SHA256()).public_bytes(serialization.Encoding.PEM).decode())
    try:
        record = _post_certificate(csr)
        fact = _owned_certificate_fact(record, key_sha, before_ids, team)
        receipt.update(fact, status="CREATED_TASK_OWNED_DEVELOPMENT_IDENTITY")
    except CertificateCreationRejected as error:
        receipt.update(status="APPLE_CERTIFICATE_API_REJECTED", http_status=error.status,
                       apple_error_codes=error.codes, native_archive="NOT_REQUESTED")
        raise
    except Exception:
        # Do not POST a second time. A matching SPKI proves ownership even when
        # the first HTTP response was lost. Otherwise retain the private key.
        receipt["status"] = "CERTIFICATE_OUTCOME_REQUIRES_RECONCILIATION"
        matches = []
        for candidate in _development_certificates():
            try:
                matches.append((candidate, _owned_certificate_fact(candidate, key_sha, before_ids, team)))
            except (ValueError, KeyError):
                continue
        if len(matches) != 1:
            raise CertificateCreationUncertain("Task key retained for exact certificate reconciliation") from None
        record, fact = matches[0]
        receipt.update(fact, status="RECONCILED_TASK_OWNED_DEVELOPMENT_IDENTITY")
    certificate = x509.load_der_x509_certificate(decode(record["attributes"]["certificateContent"]))
    import_password = secrets.token_hex(24)
    container = Path(work) / "owned-development.p12"
    try:
        descriptor = os.open(container, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(serialize_key_and_certificates(
                b"Hanlin task-owned development", key, certificate, None,
                serialization.BestAvailableEncryption(import_password.encode())))
        _private_output(["security", "import", container, "-P", import_password,
                         "-T", "/usr/bin/codesign", "-f", "pkcs12", "-k", keychain])
        _private_output(["security", "set-key-partition-list", "-S", "apple-tool:,apple:,codesign:",
                         "-s", "-k", keychain_password, keychain])
    finally:
        container.unlink(missing_ok=True)
    from owner_profile_readback import _identity_fingerprints
    identities = _identity_fingerprints(_private_output(
        ["security", "find-identity", "-v", "-p", "codesigning", keychain]).decode())
    if receipt["public_certificate_sha1"] not in identities:
        raise RuntimeError("Created development identity lacks local codesigning trust")
    receipt.update(status="TASK_DEVELOPMENT_IDENTITY_READY", private_key_in_owned_temporary_keychain=True)
    return receipt["public_certificate_sha1"]


def _remove_owned_private_key(receipt):
    from cryptography.hazmat.primitives import serialization
    path = Path(receipt["private_key_path"])
    root = (Path.home() / "Library/Application Support/HanlinSigningTasks").resolve()
    if (path.is_symlink() or root not in path.resolve().parents
            or path.stat().st_uid != os.getuid() or path.name != "development-private.pem"):
        raise ValueError("Task private-key cleanup path differs from the owned context")
    key = serialization.load_pem_private_key(path.read_bytes(), password=None)
    if hashlib.sha256(_public_key_bytes(key.public_key())).hexdigest() != receipt["public_key_sha256"]:
        raise ValueError("Task private-key cleanup requires an exact public key match")
    path.unlink()
    path.parent.rmdir()
    receipt.pop("private_key_path", None)
    receipt["private_key_cleanup"] = "REMOVED_EXACT_TASK_KEY"


def cleanup_task_development_identity(receipt, before_ids):
    if not receipt:
        return
    if receipt.get("public_key_matches_task_owned_private_key"):
        _revoke_temporary_development_certificate(receipt, before_ids)
        receipt["certificate_cleanup"] = "REVOKED_EXACT_TASK_CREATED_CERTIFICATE"
    elif receipt.get("status") == "APPLE_CERTIFICATE_API_REJECTED":
        receipt["certificate_cleanup"] = "NO_CERTIFICATE_CREATED_API_REJECTED"
    else:
        receipt["certificate_cleanup"] = "RECONCILIATION_REQUIRED_NO_EXISTING_IDENTITY_TOUCHED"
        raise RuntimeError("Uncertain certificate creation retained its exact private key in the owned runner context")
    _remove_owned_private_key(receipt)
