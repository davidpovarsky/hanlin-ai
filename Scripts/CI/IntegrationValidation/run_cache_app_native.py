#!/usr/bin/env python3
"""Run original AI_HLY app preparation and four cache integration suites.

Use fresh --evidence for prepare, review/commit updated working locks, then test
with the same evidence. No host-tool installation, PATH/Xcode change, lock restore,
fake CI identity, or smaller app is used. Original recipe:
.github/workflows/build-ios26-unsigned-ipa.yml.
"""
from __future__ import annotations
import argparse
import datetime
import hashlib
import json
import os
from pathlib import Path
import plistlib
import re
import shlex
import signal
import shutil
import subprocess
import sys
import textwrap
from verify_cache_app_tests import SUITES, source_inventory

ROOT = Path(__file__).resolve().parents[3]
WORKFLOW = ROOT / ".github/workflows/build-ios26-unsigned-ipa.yml"
SELECTORS = tuple("AI_HLYTests/" + suite for suite in SUITES)
IMPORT_SETTINGS = (
    "CLANG_CXX_LANGUAGE_STANDARD", "FRAMEWORK_SEARCH_PATHS", "HEADER_SEARCH_PATHS",
    "CLANG_ALLOW_NON_MODULAR_INCLUDES_IN_FRAMEWORK_MODULES",
    "CLANG_WARN_QUOTED_INCLUDE_IN_FRAMEWORK_HEADER", "WARNING_CFLAGS", "OTHER_CFLAGS",
    "OTHER_SWIFT_FLAGS", "ENABLE_TESTABILITY",
)


def utc():
    return datetime.datetime.now(datetime.timezone.utc).isoformat()


def sha(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def write_json(path, value):
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n")
    temporary.replace(path)


def git(*arguments):
    return subprocess.check_output(["git", "-C", str(ROOT), *arguments])


def is_active_package_lock(name, files):
    """Classify live lock locations using this same captured source inventory."""
    if name in {"Package.resolved",
                "AI_HLY.xcodeproj/project.xcworkspace/xcshareddata/swiftpm/Package.resolved"}:
        return True
    path = Path(name)
    return (len(path.parts) == 3 and path.parts[0] == "Packages"
            and path.name == "Package.resolved"
            and str(path.with_name("Package.swift")) in files)


def compare_sources(before, after, phase):
    changed = sorted(name for name in before["files"].keys() | after["files"].keys()
                     if before["files"].get(name) != after["files"].get(name))
    inventory = before["files"] | after["files"]
    changed_locks = [name for name in changed if is_active_package_lock(name, inventory)]
    allowed = set(changed_locks) | {"Config.xcconfig"} if phase == "prepare" else set()
    unexpected = before["sourceSHA"] != after["sourceSHA"] or bool(set(changed) - allowed)
    return changed, changed_locks, unexpected


def snapshot(folder, label):
    tracked = {os.fsdecode(name) for name in git("ls-files", "-z").split(b"\0") if name}
    extra = {ROOT / "Config.xcconfig", ROOT / "Package.resolved"}
    extra.update((ROOT / "Packages").glob("*/Package.resolved"))
    names = tracked | {str(path.relative_to(ROOT)) for path in extra if path.is_file()}
    files, missing = {}, []
    for name in sorted(names):
        path = ROOT / name
        if path.is_file():
            files[name] = sha(path)
        elif path.is_symlink():
            files[name] = hashlib.sha256(os.fsencode(os.readlink(path))).hexdigest()
        else:
            missing.append(name)
    if missing:
        raise RuntimeError("Tracked inputs are not materialized: " + ", ".join(missing[:12]))
    locks = {name: digest for name, digest in files.items() if is_active_package_lock(name, files)}
    for name in locks:
        destination = folder / (label + "-locks") / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / name, destination)
    value = {
        "sourceSHA": git("rev-parse", "HEAD").decode().strip(), "files": files, "locks": locks,
        "trackedDiffSHA256": hashlib.sha256(git("diff", "--binary", "HEAD", "--", ".")).hexdigest(),
    }
    write_json(folder / (label + "-sources.json"), value)
    return value


def original_config():
    source = WORKFLOW.read_text()
    start = source.rindex("      - name: Create CI Config.xcconfig")
    start = source.index("          cat > Config.xcconfig <<EOF\n", start)
    start = source.index("\n", start) + 1
    end = source.index("\n          EOF", start)
    content = textwrap.dedent(source[start:end]) + "\n"
    content = content.replace("$repo_root", str(ROOT)).replace(r"\$", "$")
    content = content.replace("Generated by GitHub Actions for CI builds.",
                              "Original simulator CI configuration for local validation.")
    if "$" + "{{" in content or any(key + " =\n" not in content
                                  for key in ("HANLIN_API_KEY", "HANLIN_OPEN_API_KEY")):
        raise RuntimeError("The original blank CI configuration changed; review it")
    return content


def original_import_settings():
    """Reuse the actual simulator build command's global package importer flags."""
    source = WORKFLOW.read_text()
    start = source.index("      - name: Build full arm64 simulator app")
    end = source.find("\n      - name:", start + 1)
    block = source[start:end if end != -1 else None]
    settings = {}
    for line in block.splitlines():
        line = line.strip().removesuffix("\\").rstrip()
        name = line.split("=", 1)[0]
        if name not in IMPORT_SETTINGS:
            continue
        tokens = shlex.split(line)
        if len(tokens) != 1:
            raise RuntimeError("Unexpected original build setting: " + name)
        settings[name] = tokens[0].replace("$repo_root", str(ROOT)).replace(r"\$", "$")
    if set(settings) != set(IMPORT_SETTINGS):
        raise RuntimeError("Original simulator importer settings are incomplete")
    return [settings[name] for name in IMPORT_SETTINGS]


def preparation_inputs(files):
    return {name: digest for name, digest in files.items()
            if is_active_package_lock(name, files)
            or Path(name).name in {"Package.swift", "project.pbxproj",
                                   "Config.xcconfig", "RuntimeDependencies.lock.json"}
            or name.endswith(".xcscheme")
            or name in {str(WORKFLOW.relative_to(ROOT)),
                        "Scripts/CI/stage_modular_headers.py", "Scripts/CI/stage_a2ui_schemas.py",
                        "Scripts/SDK/generate_manifest.py", "Scripts/SDK/update_project.py"}}


class Run:
    def __init__(self, phase, evidence, derived):
        self.phase, self.evidence, self.derived = phase, evidence, derived
        self.folder = evidence / phase
        self.folder.mkdir(parents=True, exist_ok=False)
        self.receipt = self.folder / "receipt.json"
        self.inventory = source_inventory(ROOT)
        write_json(self.folder / "expected-test-inventory.json", self.inventory)
        self.state = {
            "phase": phase, "status": "RUNNING", "startedAtUTC": utc(),
            "repository": str(ROOT), "derivedData": str(derived),
            "recipe": str(WORKFLOW.relative_to(ROOT)), "recipeSHA256": sha(WORKFLOW),
            "selectors": list(SELECTORS), "commands": [], "actions": [],
            "declaredTestCounts": {suite: len(methods) for suite, methods in self.inventory["suites"].items()},
            "expectedMethodCount": self.inventory["expectedMethodCount"],
            "expectedInvocationCount": self.inventory["expectedInvocationCount"],
            "expectedInventorySHA256": sha(self.folder / "expected-test-inventory.json"),
            "python": sys.executable, "developerDirectory": os.environ.get("DEVELOPER_DIR"),
            "executables": {name: shutil.which(name) for name in ("xcodebuild", "xcrun", "node", "npm")},
        }
        self.save()

    def save(self):
        write_json(self.receipt, self.state)

    def command(self, name, argv, *, check=True, json_output=False):
        argv = [str(value) for value in argv]
        number = len(self.state["commands"]) + 1
        output = self.folder / (f"{number:02d}-{name}" + (".json" if json_output else ".log"))
        error_output = output.with_suffix(".stderr.log")
        record = {"name": name, "argv": argv, "cwd": str(ROOT), "startedAtUTC": utc(),
                  "stdout": output.name, "stderr": error_output.name, "exitCode": None}
        self.state["commands"].append(record)
        self.save()
        print(f"[{self.phase}] {name}: {shlex.join(argv)}", flush=True)
        try:
            with output.open("wb") as stdout, error_output.open("wb") as stderr:
                result = subprocess.run(argv, cwd=ROOT, stdout=stdout, stderr=stderr)
            record["exitCode"] = result.returncode
        finally:
            record["finishedAtUTC"] = utc()
            record["stdoutSHA256"] = sha(output) if output.exists() else None
            record["stderrSHA256"] = sha(error_output) if error_output.exists() else None
            self.save()
        if check and result.returncode:
            raise RuntimeError(f"{name} exited {result.returncode}; see {output}")
        return result.returncode, output

    def prepare(self):
        config = ROOT / "Config.xcconfig"
        if not config.exists():
            with config.open("x") as stream:
                stream.write(original_config())
            self.state["actions"].append({"created": "Config.xcconfig", "sha256": sha(config)})
            self.save()
        self.command("manifest-check", [sys.executable, "Scripts/SDK/generate_manifest.py", "--check"])
        self.command("project-check", [sys.executable, "Scripts/SDK/update_project.py", "--check"])
        packages = ROOT / "build/SourcePackages"
        self.command("resolve-packages", ["xcodebuild", "-project", "AI_HLY.xcodeproj",
                     "-scheme", "AI_HLY", "-resolvePackageDependencies",
                     "-clonedSourcePackagesDirPath", packages,
                     "-skipPackagePluginValidation", "-skipMacroValidation"])
        self.command("modular-headers", [sys.executable, "Scripts/CI/stage_modular_headers.py",
                     "--source-packages-path", packages, "--expo-artifacts-path",
                     ROOT / "Packages/HanlinExpoRuntime/Artifacts",
                     "--derived-data-path", self.derived, "--configuration", "Debug"])
        self.command("a2ui-schemas", [sys.executable, "Scripts/CI/stage_a2ui_schemas.py",
                     "--source-packages-path", packages, "--derived-data-path", self.derived,
                     "--evidence", self.folder / "a2ui-generation"])

    def test(self, before):
        if any(before["files"].get(name) != digest
               for name, digest in self.inventory["sourceFiles"].items()):
            raise RuntimeError("Test declarations changed while capturing the source inventory")
        prepared = json.loads((self.evidence / "prepare/receipt.json").read_text())
        if prepared["status"] != "PREPARED" or prepared["derivedData"] != str(self.derived):
            raise RuntimeError("Complete prepare for this DerivedData and evidence directory first")
        previous = json.loads((self.evidence / "prepare/after-sources.json").read_text())
        if preparation_inputs(previous["files"]) != preparation_inputs(before["files"]):
            raise RuntimeError("Prepared graph, configuration or locks changed; run prepare with fresh evidence")
        lock_paths = list(before["locks"])
        if lock_paths and git("diff", "HEAD", "--", *lock_paths):
            raise RuntimeError("Review and commit resolver-updated tracked locks before test")
        products = self.derived / "Build/Products"
        archive = self.folder / "prior-xctestrun"
        archive.mkdir()
        retained = []
        for descriptor in sorted(products.glob("*.xctestrun")):
            retained.append({"name": descriptor.name, "sha256": sha(descriptor)})
            descriptor.rename(archive / descriptor.name)
        self.state["actions"].append({"archivedPriorDescriptors": retained})
        self.save()
        flags = ["-only-testing:" + value for value in SELECTORS]
        self.command("build-for-testing", [
            "xcodebuild", "-project", "AI_HLY.xcodeproj", "-scheme", "AI_HLY",
            "-configuration", "Debug", "-destination", "generic/platform=iOS Simulator",
            "-derivedDataPath", self.derived, "-clonedSourcePackagesDirPath", ROOT / "build/SourcePackages",
            "-resultBundlePath", self.folder / "AppBuild.xcresult", "-jobs", "2",
            "-showBuildTimingSummary", "-skipPackagePluginValidation", "-skipMacroValidation",
            *original_import_settings(), "IPHONEOS_DEPLOYMENT_TARGET=27.0", "ARCHS=arm64",
            "ONLY_ACTIVE_ARCH=YES", "SWIFT_ACTIVE_COMPILATION_CONDITIONS=$(inherited) HANLIN_TESTING",
            *flags, "build-for-testing",
        ])
        manifests = list(products.glob("AI_HLY_*.xctestrun"))
        if len(manifests) != 1:
            raise RuntimeError("Expected one newly generated original AI_HLY .xctestrun")
        manifest = manifests[0]
        plistlib.loads(manifest.read_bytes())
        shutil.copyfile(manifest, self.folder / "current-generated.xctestrun")
        self.state["generatedXctestrun"] = {"path": str(manifest), "sha256": sha(manifest)}
        self.save()
        simulator = None
        try:
            name = "Hanlin-AI-Cache-" + before["sourceSHA"][:8] + "-" + self.folder.parent.name
            _, created = self.command("create-simulator", ["xcrun", "simctl", "create", name,
                "com.apple.CoreSimulator.SimDeviceType.iPhone-18-Pro",
                "com.apple.CoreSimulator.SimRuntime.iOS-27-0"])
            simulator = created.read_text().strip()
            if not re.fullmatch(r"[0-9a-fA-F]{8}(?:-[0-9a-fA-F]{4}){3}-[0-9a-fA-F]{12}", simulator):
                simulator = None
                raise RuntimeError("simctl did not return an owned simulator UUID")
            self.state["ownedSimulator"] = simulator
            self.save()
            self.command("boot-simulator", ["xcrun", "simctl", "boot", simulator])
            self.command("bootstatus", ["xcrun", "simctl", "bootstatus", simulator, "-b"])
            result_bundle = self.folder / "AppCacheTests.xcresult"
            test_exit, _ = self.command("test-without-building", [
                "xcodebuild", "test-without-building", "-xctestrun", manifest,
                "-destination", "platform=iOS Simulator,id=" + simulator,
                "-resultBundlePath", result_bundle, "-parallel-testing-enabled", "NO",
                "-test-timeouts-enabled", "YES", "-maximum-test-execution-time-allowance", "300",
                *flags], check=False)
            self.state["testExitCode"] = test_exit
            self.save()
            _, result_file = self.command("test-results", ["xcrun", "xcresulttool", "get",
                "test-results", "tests", "--path", result_bundle, "--format", "json"], json_output=True)
            verify_exit, _ = self.command("verify-selected-tests", [sys.executable,
                "Scripts/CI/verify_selected_tests.py", "--results", result_file,
                "--selectors", ",".join(SELECTORS)], check=False)
            if sha(self.folder / "expected-test-inventory.json") != self.state["expectedInventorySHA256"]:
                raise RuntimeError("Captured source test inventory changed during execution")
            exact_exit, exact_file = self.command("verify-exact-test-invocations", [sys.executable,
                "Scripts/CI/IntegrationValidation/verify_cache_app_tests.py",
                "--inventory", self.folder / "expected-test-inventory.json",
                "--results", result_file], check=False, json_output=True)
            exact = json.loads(exact_file.read_text())
            self.state["exactTestAcceptance"] = exact
            self.state["executedCases"] = [case for case in exact["cases"]
                                           if case.get("node_identifier_url")]
            self.state["executedCount"] = exact["observedInvocationCount"]
            self.state["passedInvocationCount"] = exact["passedInvocationCount"]
            self.save()
            if test_exit or verify_exit or exact_exit or exact["status"] != "PASS":
                raise RuntimeError("Every selected source-declared test invocation must be present once and Passed")
        finally:
            if simulator:
                shutdown, _ = self.command("shutdown-owned-simulator",
                    ["xcrun", "simctl", "shutdown", simulator], check=False)
                self.state["simulatorShutdownExitCode"] = shutdown
                self.save()
                if shutdown and sys.exc_info()[0] is None:
                    raise RuntimeError("Owned simulator shutdown failed; see its retained log")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--phase", choices=("prepare", "test"), required=True)
    parser.add_argument("--derived", type=Path, required=True)
    parser.add_argument("--evidence", type=Path, required=True)
    args = parser.parse_args()
    if sys.platform != "darwin" or sys.version_info < (3, 11):
        parser.error("Run on the authorized Mac with the existing Python >=3.11 and Node24 PATH")
    derived, evidence = args.derived.resolve(), args.evidence.resolve()
    if derived == ROOT or ROOT.is_relative_to(derived):
        parser.error("--derived must be a dedicated independent DerivedData directory")
    def interrupted(signum, _frame):
        raise KeyboardInterrupt("Interrupted by signal " + str(signum))
    signal.signal(signal.SIGTERM, interrupted)
    run = Run(args.phase, evidence, derived)
    before, error = None, None
    try:
        before = snapshot(run.folder, "before")
        run.state["sourceSHA"] = before["sourceSHA"]
        run.save()
        run.command("xcode-version", ["xcodebuild", "-version"])
        run.command("swift-version", ["xcrun", "swift", "--version"])
        run.command("node-version", ["node", "--version"])
        run.prepare() if args.phase == "prepare" else run.test(before)
    except (Exception, KeyboardInterrupt) as caught:
        error = str(caught) or type(caught).__name__
    finally:
        try:
            after = snapshot(run.folder, "after")
            run.state["sourceSHAAfter"] = after["sourceSHA"]
            if before:
                changed, changed_locks, unexpected = compare_sources(before, after, args.phase)
                run.state["changedSourcePaths"] = changed
                run.state["changedLockPaths"] = changed_locks
                if unexpected:
                    error = error or "Source inputs changed during this phase"
        except Exception as caught:
            error = error or "Cannot retain final source evidence: " + str(caught)
        run.state.update(finishedAtUTC=utc(), status="FAILED" if error else (
            "PREPARED" if args.phase == "prepare" else "PASS"))
        if error:
            run.state["error"] = error
        run.save()
    print(json.dumps({"status": run.state["status"], "receipt": str(run.receipt),
                      "changedLockPaths": run.state.get("changedLockPaths", []),
                      "error": error}, indent=2), flush=True)
    return 1 if error else 0


if __name__ == "__main__":
    raise SystemExit(main())
