// Generate the existing NativeScript metadata facade and declarations together.
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
const root = path.resolve(import.meta.dirname, '../..');
const argument = process.argv.indexOf('--typescript-module');
const compiler = argument < 0 ? createRequire(import.meta.url).resolve('typescript') : path.resolve(process.argv[argument + 1]);
const ts = (await import(pathToFileURL(compiler).href)).default;
const input = path.join(import.meta.dirname, 'host-services.ts');
const output = path.join(root, 'Packages/HanlinNativeScriptRuntime/Sources/HanlinNativeScriptRuntime/Resources/NativeScriptSharedRuntime/@hanlin/host-services');
const files = new Map();
// This standalone facade needs no implicit @types packages from ancestor workspaces.
const options = {strict: true, skipLibCheck: false, types: [], noEmitOnError: true, declaration: true,
  target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022, moduleResolution: ts.ModuleResolutionKind.Bundler};
const program = ts.createProgram([input], options);
const diagnostics = ts.getPreEmitDiagnostics(program);
if (diagnostics.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(diagnostics, {
  getCanonicalFileName: p => p, getCurrentDirectory: () => root, getNewLine: () => '\n'}));
const fixture = name => path.join(import.meta.dirname, 'Fixtures/HostServices', name + '.ts');
const valid = ts.getPreEmitDiagnostics(ts.createProgram([fixture('valid'), fixture('live-activities'), fixture('assistant')], {...options, noEmit: true}));
if (valid.length) throw new Error('The public NativeScript runtime facade example does not typecheck.');
const invalid = ts.getPreEmitDiagnostics(ts.createProgram([fixture('invalid')], {...options, noEmit: true}));
const expectedCodes = [2322, 2345, 2353, 7006];
if (JSON.stringify(invalid.map(d => d.code).sort((a, b) => a - b)) !== JSON.stringify(expectedCodes)) {
  throw new Error(`NativeScript negative fixture diagnostics drifted: ${invalid.map(d => d.code).join(',')}`);
}
const hash = createHash('sha256').update(await readFile(input))
  .update(await readFile(path.join(root, 'Packages/HanlinExpoUI/src/system-surfaces.ts')))
  .update(await readFile(path.join(root, 'Packages/HanlinExpoUI/src/miniapp-assistant.ts'))).digest('hex');
const banner = `// Generated by TypeScript${ts.version} from Scripts/NativeScript/host-services.ts; SHA256 ${hash}\n`;
const emitted = program.emit(undefined, (file, text) => {
  const base = path.basename(file);
  const stem = base.startsWith('system-surfaces.') ? 'system-surfaces'
    : base.startsWith('miniapp-assistant.') ? 'miniapp-assistant' : 'index';
  const portable = text.replaceAll('../../Packages/HanlinExpoUI/src/system-surfaces', './system-surfaces')
    .replaceAll('../../Packages/HanlinExpoUI/src/miniapp-assistant', file.endsWith('.d.ts') ? './miniapp-assistant' : './miniapp-assistant.mjs');
  files.set(stem + (file.endsWith('.d.ts') ? '.d.ts' : '.mjs'), banner + portable.replaceAll('\r\n', '\n'));
});
if (emitted.emitSkipped || files.size !== 6) throw new Error('NativeScript Host Services did not emit both JS and declarations.');
files.set('package.json', JSON.stringify({name: '@hanlin/host-services', version: '1.0.0', private: true,
  type: 'module', main: 'index.mjs', types: 'index.d.ts'}, null, 2) + '\n');
if (process.argv.includes('--write')) {
  await mkdir(output, {recursive: true});
  for (const [name, bytes] of files) await writeFile(path.join(output, name), bytes);
} else if (process.argv.includes('--check')) {
  for (const [name, bytes] of files) if (await readFile(path.join(output, name), 'utf8') !== bytes) throw new Error(`Generated NativeScript Host Services drift: ${name}`);
} else throw new Error('Use --write after reviewing source changes, or --check for read-only compiler/drift verification.');
console.log(`PASS: TypeScript${ts.version} strict native facade, declarations and JS ${process.argv.includes('--write') ? 'generated' : 'unchanged'}; native execution is a separate gate.`);
